package com.github.kookaburra.processor;

import java.io.IOException;
import java.io.Writer;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.NestingKind;
import javax.lang.model.element.PackageElement;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.VariableElement;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.PrimitiveType;
import javax.lang.model.type.TypeKind;
import javax.lang.model.type.TypeMirror;
import javax.lang.model.util.ElementFilter;
import javax.tools.Diagnostic;

/**
 * Generates a metamodel class {@code X_} for every {@code @Entity X}, e.g.
 * {@code Person_.age}, {@code Person_.home.city}. Field kinds mirror {@code com.github.kookaburra.field.Fields}
 * so generated constants and {@code where(Person::getX)} resolve to the same interned instances.
 *
 * @Author: Fred Feng
 * @Date: 11/10/2026
 * @Version 1.0.0
 */
@SupportedAnnotationTypes(MetamodelProcessor.ENTITY)
public class MetamodelProcessor extends AbstractProcessor {

    static final String ENTITY = "com.github.kookaburra.annotation.Entity";
    private static final String EMBEDDABLE = "com.github.kookaburra.annotation.Embeddable";
    private static final String TRANSIENT = "com.github.kookaburra.annotation.Transient";
    private static final String REF = "com.github.kookaburra.Ref";
    private static final String F = "com.github.kookaburra.field.";
    private static final int MAX_EMBEDDED_DEPTH = 8;

    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment round) {
        for (TypeElement annotation : annotations) {
            for (Element e : round.getElementsAnnotatedWith(annotation)) {
                if (e.getKind() != ElementKind.CLASS) {
                    error(e, "@Entity must be placed on a class");
                    continue;
                }
                TypeElement entity = (TypeElement) e;
                if (!entity.getTypeParameters().isEmpty()) {
                    error(e, "@Entity classes cannot be generic");
                    continue;
                }
                if (entity.getNestingKind() == NestingKind.MEMBER && !entity.getModifiers().contains(Modifier.STATIC)) {
                    error(e, "@Entity member classes must be static");
                    continue;
                }
                try {
                    generate(entity);
                } catch (IOException | RuntimeException ex) {
                    error(e, "Cannot generate metamodel: " + ex);
                }
            }
        }
        return false;
    }

    // ---------------------------------------------------------------- generation

    private void generate(TypeElement entity) throws IOException {
        String pkg = processingEnv.getElementUtils().getPackageOf(entity).getQualifiedName().toString();
        String name = metamodelName(entity);
        String entityName = entity.getQualifiedName().toString();
        StringBuilder out = new StringBuilder();
        if (!pkg.isEmpty()) {
            out.append("package ").append(pkg).append(";\n\n");
        }
        out.append("/** Metamodel of {@link ").append(entityName).append("}, generated by kookaburra-processor. */\n");
        out.append("@javax.annotation.processing.Generated(\"").append(getClass().getName()).append("\")\n");
        out.append("public class ").append(name).append(" {\n\n");
        out.append("    private ").append(name).append("() {\n    }\n");
        members(out, "    ", true, entityName, "", entity, new HashSet<>(), 0);
        out.append("}\n");

        String qualified = pkg.isEmpty() ? name : pkg + "." + name;
        try (Writer w = processingEnv.getFiler().createSourceFile(qualified, entity).openWriter()) {
            w.write(out.toString());
        }
    }

    /** Emits one constant per persistent field of {@code type}; embedded fields become nested path classes. */
    private void members(StringBuilder out, String indent, boolean statics, String entity, String prefix,
                         TypeElement type, Set<String> embeddedStack, int depth) {
        String mod = statics ? "public static final " : "public final ";
        for (VariableElement field : persistentFields(type).values()) {
            String fname = field.getSimpleName().toString();
            String path = prefix + fname;
            TypeMirror t = field.asType();
            Kind k = classify(t);
            out.append('\n');
            if (k.kind == null) {
                TypeElement embedded = asElement(t);
                String embeddedName = embedded.getQualifiedName().toString();
                if (depth >= MAX_EMBEDDED_DEPTH || !embeddedStack.add(embeddedName)) {
                    error(field, "Recursive or too deep @Embeddable path: " + path);
                    continue;
                }
                String cls = Character.toUpperCase(fname.charAt(0)) + fname.substring(1) + "_";
                out.append(indent).append(mod).append(cls).append(' ').append(fname)
                        .append(" = new ").append(cls).append("();\n\n");
                out.append(indent).append("public ").append(statics ? "static " : "").append("class ").append(cls)
                        .append(" extends ").append(F).append("EmbeddedPath<").append(entity).append(", ")
                        .append(embeddedName).append("> {\n");
                out.append(indent).append("    ").append(cls).append("() {\n")
                        .append(indent).append("        super(").append(entity).append(".class, \"").append(path)
                        .append("\");\n").append(indent).append("    }\n");
                members(out, indent + "    ", false, entity, path + ".", embedded, embeddedStack, depth + 1);
                out.append(indent).append("}\n");
                embeddedStack.remove(embeddedName);
            } else {
                String typeArgs = k.extraTypeArg == null ? entity : entity + ", " + k.extraTypeArg;
                out.append(indent).append(mod).append(F).append(k.kind).append('<').append(typeArgs).append("> ")
                        .append(fname).append(" =\n").append(indent).append("        ").append(F).append("Fields.")
                        .append(k.factory).append('(').append(entity).append(".class, \"").append(path).append("\");\n");
            }
        }
    }

    /** Persistent fields of a class and its superclasses; subclass declarations shadow superclass ones. */
    private Map<String, VariableElement> persistentFields(TypeElement type) {
        List<TypeElement> hierarchy = new ArrayList<>();
        for (TypeElement t = type; t != null && !t.getQualifiedName().contentEquals("java.lang.Object"); t = superclass(t)) {
            hierarchy.add(0, t);
        }
        Map<String, VariableElement> fields = new LinkedHashMap<>();
        for (TypeElement t : hierarchy) {
            for (VariableElement f : ElementFilter.fieldsIn(t.getEnclosedElements())) {
                String n = f.getSimpleName().toString();
                fields.remove(n);
                if (isPersistent(f)) {
                    fields.put(n, f);
                }
            }
        }
        return fields;
    }

    private TypeElement superclass(TypeElement t) {
        TypeMirror s = t.getSuperclass();
        return s.getKind() == TypeKind.DECLARED ? (TypeElement) ((DeclaredType) s).asElement() : null;
    }

    private static boolean isPersistent(VariableElement f) {
        Set<Modifier> m = f.getModifiers();
        return !m.contains(Modifier.STATIC) && !m.contains(Modifier.TRANSIENT) && !hasAnnotation(f, TRANSIENT);
    }

    // ---------------------------------------------------------------- classification (mirrors ValueType.of)

    /** Field class, factory method and optional second type argument; {@code kind == null} = embedded. */
    private record Kind(String kind, String factory, String extraTypeArg) {
    }

    private Kind classify(TypeMirror t) {
        switch (t.getKind()) {
            case BOOLEAN: return new Kind("BoolField", "boolField", null);
            case INT: case SHORT: case BYTE: case CHAR: return new Kind("IntField", "intField", null);
            case LONG: return new Kind("LongField", "longField", null);
            case FLOAT: case DOUBLE: return new Kind("DoubleField", "doubleField", null);
            case DECLARED: break;
            default: return object(t);
        }
        TypeElement e = asElement(t);
        String n = e.getQualifiedName().toString();
        switch (n) {
            case "java.lang.Boolean": return new Kind("BoolField", "boolField", null);
            case "java.lang.Integer": case "java.lang.Short": case "java.lang.Byte": case "java.lang.Character":
                return new Kind("IntField", "intField", null);
            case "java.lang.Long": return new Kind("LongField", "longField", null);
            case "java.lang.Double": case "java.lang.Float": return new Kind("DoubleField", "doubleField", null);
            case "java.lang.String": return new Kind("StringField", "stringField", null);
            case "java.time.LocalDate": case "java.time.LocalDateTime": case "java.time.Instant":
                return new Kind("ComparableField", "comparableField", n);
            case REF: return new Kind("RefField", "refField", typeArg(t, 0));
            default: break;
        }
        if (e.getKind() == ElementKind.ENUM) {
            return new Kind("EnumField", "enumField", n);
        }
        if (isCollection(t)) {
            String elem = typeArg(t, 0);
            TypeMirror elemType = typeArgMirror(t, 0);
            if (elemType != null && isScalar(elemType)) {
                return new Kind("ListField", "listField", elem);
            }
            return object(t);
        }
        if (hasAnnotation(e, EMBEDDABLE)) {
            return new Kind(null, null, null);
        }
        return object(t);
    }

    private Kind object(TypeMirror t) {
        return new Kind("ObjectField", "objectField", boxedName(t));
    }

    private boolean isScalar(TypeMirror t) {
        Kind k = classify(t);
        return k.kind != null && !k.kind.equals("ListField") && !k.kind.equals("ObjectField");
    }

    private boolean isCollection(TypeMirror t) {
        TypeMirror collection = processingEnv.getTypeUtils().erasure(
                processingEnv.getElementUtils().getTypeElement("java.util.Collection").asType());
        return processingEnv.getTypeUtils().isAssignable(processingEnv.getTypeUtils().erasure(t), collection);
    }

    private TypeMirror typeArgMirror(TypeMirror t, int i) {
        List<? extends TypeMirror> args = ((DeclaredType) t).getTypeArguments();
        return args.size() > i && args.get(i).getKind() == TypeKind.DECLARED ? args.get(i) : null;
    }

    private String typeArg(TypeMirror t, int i) {
        TypeMirror a = typeArgMirror(t, i);
        return a == null ? "java.lang.Object" : a.toString();
    }

    private String boxedName(TypeMirror t) {
        if (t.getKind().isPrimitive()) {
            return processingEnv.getTypeUtils().boxedClass((PrimitiveType) t)
                    .getQualifiedName().toString();
        }
        return t.toString();
    }

    private static TypeElement asElement(TypeMirror t) {
        return (TypeElement) ((DeclaredType) t).asElement();
    }

    private static boolean hasAnnotation(Element e, String name) {
        return e.getAnnotationMirrors().stream()
                .anyMatch(a -> ((TypeElement) a.getAnnotationType().asElement()).getQualifiedName().contentEquals(name));
    }

    /** {@code Person} → {@code Person_}; nested {@code Outer.Person} → {@code Outer_Person_}. */
    private static String metamodelName(TypeElement entity) {
        StringBuilder sb = new StringBuilder();
        for (Element e = entity; !(e instanceof PackageElement); e = e.getEnclosingElement()) {
            sb.insert(0, sb.length() == 0 ? e.getSimpleName() : e.getSimpleName() + "_");
        }
        return sb.append('_').toString();
    }

    private void error(Element e, String msg) {
        processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, msg, e);
    }
}
